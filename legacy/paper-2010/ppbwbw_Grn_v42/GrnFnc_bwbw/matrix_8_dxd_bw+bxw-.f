      COMMON/BW/MT1S,MT2S,S
      DOUBLE PRECISION CORR,COR
      EXTERNAL CORR
      DOUBLE COMPLEX GAMMA
      COMPLEX*16 OV1,OV2
      include 'coupling.inc'
      include 'thr.inc'

      GRN = DCMPLX(1D0,0D0)
      IF (EI.LT.EMIN1 .OR. EI.GT.EMAX2) RETURN ! outside the grip
      IF (EI.LT.EMAX1) THEN
         IT = 1
         IF (EI.LT.EMIN1) THEN
            IE = 0
            E = EI
         ELSEIF (EI.GE.EMIN1) THEN
            E = EI
            IE = EINT(E,1)
         ELSE
            WRITE (9,*) "ERROR; IT = 1"
            STOP
         ENDIF
         PMIN = PMIN1
         PMAX = PMAX1
      ELSEIF (EI.GE.EMIN2) THEN
         IT = 2
         IF (EI.GT.EMAX2) THEN
C...  extrapolation
*            IE = NE2-1
*            E = EI
C...  stop at the maximum of grid
            E = EMAX2
            IE = NE2
         ELSEIF (EI.LE.EMAX2) THEN
            E = EI
            IE = EINT(E,2)
         ELSE
            WRITE (9,*) "ERROR; IT = 2"
            STOP
         ENDIF
         POS = DSQRT(MT*E)
         PMIN = PP (0,IT)
         PMAX = PP (NP2,IT)
      ELSE
         WRITE (9,*) "IT"
         WRITE(9,*) EI,EMIN1,EMAX1,EMIN2,EMAX2
         STOP
      ENDIF
C
      IF (PI.GT.PMAX) THEN
C...  extrapolation to outside grid
*         P = PI
*         IP = PINT(PMAX,IT) - 1
C...  stop at the maxmum
         P = PMAX
         IP = PINT(PMAX,IT)
      ELSEIF (PI.LT.PMIN) THEN
         P = PI
         IP = 0
      ELSE
         P = PI
         IP = PINT(P,IT)
      ENDIF
C
      IF (ABS(EE(IE,IT)-E).LE.1D-4 .AND. ABS(PP(IP,IT)-P).LE.1D-4) THEN
         CALL READGRNTBL (GRN,IE,IP,ICLR,IT)
*         WRITE (9,*) IE, IP, " On the Axes Inter-Section"
      ELSEIF ( ABS(PP(IP,IT)-P) .LE. 1D-4 ) THEN
         IE0 = IE
         IE1 = IE0 + 1
         E0 = EE(IE0,IT)
         E1 = EE(IE1,IT)
         CALL READGRNTBL (G0,IE0,IP,ICLR,IT)
         CALL READGRNTBL (G1,IE1,IP,ICLR,IT)
         GRN = (G1-G0)/(E1-E0)*(E-E0) + G0
*         WRITE (9,*) "On the P-Axis"
      ELSEIF ( ABS(EE(IE,IT)-E) .LE. 1D-4 ) THEN
         IP0 = IP
         IP1 = IP0 + 1
         P0 = PP(IP0,IT)
         P1 = PP(IP1,IT)
         CALL READGRNTBL (G0,IE,IP0,ICLR,IT)
         CALL READGRNTBL (G1,IE,IP1,ICLR,IT)
         GRN = (G1-G0)/(P1-P0)*(P-P0) + G0
*         WRITE (9,*) "On the E-Axis"
      ELSE
         IE0 = IE
         IE1 = IE0 + 1
         E0 = EE(IE0,IT)
         E1 = EE(IE1,IT)
         IP0 = IP
         IP1 = IP0 + 1
         P0 = PP(IP0,IT)
         P1 = PP(IP1,IT)
         CALL READGRNTBL (G00,IE0,IP0,ICLR,IT)
         CALL READGRNTBL (G01,IE0,IP1,ICLR,IT)
         G0 = (G01-G00)/(P1-P0)*(P-P0) + G00
         CALL READGRNTBL (G10,IE1,IP0,ICLR,IT)
         CALL READGRNTBL (G11,IE1,IP1,ICLR,IT)
         G1 = (G11-G10)/(P1-P0)*(P-P0) + G10
         GRN = (G1-G0)/(E1-E0)*(E-E0) + G0
      ENDIF
      RETURN
      END
C
      DOUBLE PRECISION FUNCTION EE (IE,IT)
      IMPLICIT NONE
      INTEGER IT,NE
      DOUBLE PRECISION EMIN,EMAX
      INTEGER NE1,NP1,NE2,NP2
      DOUBLE PRECISION EMIN1,EMAX1,PMIN1,PMAX1,EMIN2,EMAX2,RR,POS
      COMMON/GRN1/NE1,NP1,NE2,NP2
      COMMON/GRN2/EMIN1,EMAX1,PMIN1,PMAX1,EMIN2,EMAX2,RR,POS
      INTEGER IE
      IF (IT.EQ.1) THEN
         NE = NE1
         EMIN = EMIN1
         EMAX = EMAX1
      ELSEIF (IT.EQ.2) THEN
         NE = NE2
         EMIN = EMIN2
         EMAX = EMAX2
      ENDIF
      EE = EMIN + DBLE(IE)/DBLE(NE) * (EMAX - EMIN)
      RETURN
      END
C
      INTEGER FUNCTION EINT (E,IT)
      IMPLICIT NONE
      INTEGER IT,NE
      DOUBLE PRECISION EMIN,EMAX
      INTEGER NE1,NP1,NE2,NP2
      DOUBLE PRECISION EMIN1,EMAX1,PMIN1,PMAX1,EMIN2,EMAX2,RR,POS
      COMMON/GRN1/NE1,NP1,NE2,NP2
      COMMON/GRN2/EMIN1,EMAX1,PMIN1,PMAX1,EMIN2,EMAX2,RR,POS
      DOUBLE PRECISION E
      IF (IT.EQ.1) THEN
         NE = NE1
         EMIN = EMIN1
         EMAX = EMAX1
      ELSEIF (IT.EQ.2) THEN
         NE = NE2
         EMIN = EMIN2
         EMAX = EMAX2
      ENDIF
      EINT = INT(NE*(E-EMIN)/(EMAX-EMIN))
      RETURN
      END
C
      DOUBLE PRECISION FUNCTION PP (IP,IT)
      IMPLICIT NONE
      INTEGER IP,IT,M
      DOUBLE PRECISION PMIN,PMAX
      DOUBLE PRECISION A,R1
      INTEGER NE1,NP1,NE2,NP2
      DOUBLE PRECISION EMIN1,EMAX1,PMIN1,PMAX1,EMIN2,EMAX2,RR,POS
      COMMON/GRN1/NE1,NP1,NE2,NP2
      COMMON/GRN2/EMIN1,EMAX1,PMIN1,PMAX1,EMIN2,EMAX2,RR,POS
      IF (IT.EQ.1) THEN
         PMIN = PMIN1
         PMAX = PMAX1
         PP = PMIN + DBLE(IP)/DBLE(NP1) * (PMAX - PMIN)
      ELSEIF (IT.EQ.2) THEN
         M = (NP2-1)/2
         A = (1D0-RR)/(1D0-RR**M) * POS
         R1 = 1D0/RR
         IF (IP.LE.M) THEN
            PP = POS * (1D0-RR**(IP+1)) / (1D0-RR**(M+1))
         ELSE
            PP = POS + A*RR**M*(1D0-R1**(IP-M+1))/(1D0-R1)
         ENDIF
      ENDIF
      RETURN
      END
C
      INTEGER FUNCTION PINT (P,IT)
      IMPLICIT NONE
      DOUBLE PRECISION P,A,R1
      INTEGER IT,M
      DOUBLE PRECISION PMIN,PMAX
      INTEGER NE1,NP1,NE2,NP2
      DOUBLE PRECISION EMIN1,EMAX1,PMIN1,PMAX1,EMIN2,EMAX2,RR,POS
      COMMON/GRN1/NE1,NP1,NE2,NP2
      COMMON/GRN2/EMIN1,EMAX1,PMIN1,PMAX1,EMIN2,EMAX2,RR,POS
      IF (IT.EQ.1) THEN
         PMIN = PMIN1
         PMAX = PMAX1
         PINT = INT(NP1*(P-PMIN)/(PMAX-PMIN))
      ELSEIF (IT.EQ.2) THEN
         M = (NP2-1)/2
         A = (1D0-RR)/(1D0-RR**M) * POS
         R1 = 1D0/RR
         IF (P.LE.POS) THEN
            PINT = INT(DLOG(1D0-P/POS*(1D0-RR**(M+1)))/DLOG(RR)) - 1
         ELSE
            PINT = INT(DLOG(1D0-(P-POS)/(A*RR**M)*(1D0-R1))/DLOG(R1))
     -           + M - 1
         ENDIF
      ENDIF
      RETURN
      END
c
      subroutine fvixxz (fi,vc,gc,fmass,fwidth , fvi)
c
c This subroutine computes an off-shell fermion wavefunction from a
c flowing-IN external fermion and a vector boson.
c
c input:
c     complex fi(6)          : flow-in  fermion                   |fi>
c     complex vc(6)          : input    vector                      v
c     complex gc(2)          : coupling constants                  gvf
c     real    fmass          : mass  of output fermion f'
c     real    fwidth         : width of output fermion f'
c
c output:
c     complex fvi(6)         : off-shell fermion             |f',v,fi>
c
      implicit none
      double complex fi(6),vc(6),gc(2),fvi(6),sl1,sl2,sr1,sr2,d
      double precision pf(0:3),fmass,fwidth,pf2,pab
      double precision rZero, rOne
      parameter( rZero = 0.0d0, rOne = 1.0d0 )
      double complex cImag, cZero
      parameter( cImag = ( 0.0d0, 1.0d0 ), cZero = ( 0.0d0, 0.0d0 ) )
      DOUBLE PRECISION MT1S,MT2S,S
      COMMON/BW/MT1S,MT2S,S
      DOUBLE PRECISION DEL,LM,LAM
      EXTERNAL LAM
      DOUBLE PRECISION D1,D2
c
      integer stdo
      parameter( stdo = 6 )
c
      if ( abs(fi(1))+abs(fi(2))+abs(fi(3))+abs(fi(4)).eq.rZero ) then
         write(stdo,*) ' helas-warn  : fi in fvixxx is zero spinor'
      endif
      if ( abs(fi(5))+abs(fi(6)).eq.rZero ) then
         write(stdo,*)
     &        ' helas-error : fi in fvixxx has zero momentum'
      endif
      if ( abs(vc(1))+abs(vc(2))+abs(vc(3))+abs(vc(4)).eq.rZero ) then
         write(stdo,*) ' helas-warn  : vc in fvixxx is zero vector'
      endif
      if ( abs(vc(5))+abs(vc(6)).eq.rZero ) then
         write(stdo,*)
     &        ' helas-error : vc in fvixxx has zero momentum'
      endif
      if ( gc(1).eq.cZero .and. gc(2).eq.cZero ) then
         write(stdo,*)
     &        ' helas-error : gc in fvixxx is zero coupling'
      endif
      if ( fmass.lt.rZero ) then
         write(stdo,*) ' helas-error : fmass in fvixxx is negative'
         write(stdo,*) '             : fmass = ',fmass
      endif
      if ( fwidth.lt.rZero ) then
         write(stdo,*) ' helas-error : fwidth in fvixxx is negative'
         write(stdo,*) '             : fwidth = ',fwidth
      endif

      fvi(5) = fi(5) - vc(5)
      fvi(6) = fi(6) - vc(6)

      pf(0) = dble( fvi(5))
      pf(1) = dble( fvi(6))
      pf(2) = dimag(fvi(6))
      pf(3) = dimag(fvi(5))
      pf2 = pf(0)**2-(pf(1)**2+pf(2)**2+pf(3)**2)

      if ( abs(fvi(5))+abs(fvi(6)).eq.rZero ) then
         write(stdo,*)
     &        ' helas-error : fvi in fvixxx has zero momentum'
      endif
      if ( fwidth.eq.rZero .and. pf2.eq.fmass**2 ) then
         write(stdo,*)
     &        ' helas-error : fvi in fvixxx is on fmass pole'
         write(stdo,*)
     &        '             : p     = ',pf(0),pf(1),pf(2),pf(3)
         write(stdo,*)
     &        '             : abs(p)= ',dsqrt(dabs(pf2))
         fvi(1) = cZero
         fvi(2) = cZero
         fvi(3) = cZero
         fvi(4) = cZero
         return
      endif

      del = (2.*fmass**2 - MT1S - MT2S) / S
      lm = LAM(rOne,MT1S/S,MT2S/S)
      d1 = rOne / (S * lm) * dlog((rOne+del+lm)/(rOne+del-lm))
      d2 = rOne / (S * lm) *
     -     (2. -(rOne+del) * dlog((rOne+del+lm)/(rOne+del-lm)))

      pab = dsqrt(dble(fi(6))**2+dimag(fi(6))**2+dimag(fi(5))**2)

      pf(0) = dble(fi(5) - vc(5)) * d1
      pf(1) = dble(      - vc(6)) * d1
      pf(2) = dimag(     - vc(6)) * d1
      pf(3) = dimag(     - vc(5)) * d1
*      pf(3) = dimag(-pab*d2 - vc(5)*d1)
c
      sl1 =  (vc(1) +       vc(4)) * fi(1)
     &     + (vc(2) - cImag*vc(3)) * fi(2)
      sl2 =  (vc(2) + cImag*vc(3)) * fi(1)
     &     + (vc(1) -       vc(4)) * fi(2)
c
      sr1 =   (vc(1) -       vc(4)) * fi(3)
     &     -  (vc(2) - cImag*vc(3)) * fi(4)
      sr2 = - (vc(2) + cImag*vc(3)) * fi(3)
     &     +  (vc(1) +       vc(4)) * fi(4)
c
      fvi(1) = ( gc(1)*( (pf(0)-pf(3))*sl1 - (pf(1)-cImag*pf(2))*sl2)
     &     + gc(2)*fmass*sr1 * d1 )
      fvi(2) = ( gc(1)*(-(pf(1)+cImag*pf(2))*sl1 + (pf(0)+pf(3))*sl2)
     &     + gc(2)*fmass*sr2 * d1 )
      fvi(3) = ( gc(2)*( (pf(0)+pf(3))*sr1 + (pf(1)-cImag*pf(2))*sr2)
     &     + gc(1)*fmass*sl1 * d1 )
      fvi(4) = ( gc(2)*( (pf(1)+cImag*pf(2))*sr1 + (pf(0)-pf(3))*sr2)
     &     + gc(1)*fmass*sl2 * d1 )
c
      return
      end
c
c
      DOUBLE PRECISION FUNCTION LAM (A,B,C)
      IMPLICIT NONE
      DOUBLE PRECISION A,B,C
      LAM = DSQRT(MAX(A**2+B**2+C**2-2D0*A*B-2D0*B*C-2D0*C*A, 0D0))
      RETURN
      END

C
      DOUBLE PRECISION FUNCTION LAM (A,B,C)
      IMPLICIT NONE
      DOUBLE PRECISION A,B,C
      LAM = A**2 + B**2 + C**2 - 2D0*A*B - 2D0*B*C - 2D0*C*A
      LAM = DSQRT(MAX(LAM,0D0))
      RETURN
      END

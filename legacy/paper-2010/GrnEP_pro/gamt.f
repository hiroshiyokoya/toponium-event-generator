      DOUBLE PRECISION FUNCTION RGAMT (P,GF,MW,MB,VTB)
      IMPLICIT NONE
      DOUBLE PRECISION P,GF,MW,MB,VTB
      DOUBLE PRECISION MW2,MB2,P2
      DOUBLE PRECISION X,Y,GT0,A0,A1
      DOUBLE PRECISION PI,SQ2,CF
      PARAMETER ( PI=3.141592654D0,SQ2=1.41421356D0,CF=1.3333333D0 )
      P2 = P**2
      MW2 = MW**2
      MB2 = MB**2
      X = MW2/P2
      Y = MB2/P2
      GT0 = GF*VTB**2 / (8D0*SQ2*PI) * P**3
      A0 = (1D0-Y)**2 + X*(1D0+Y) - 2D0*X**2
      RGAMT = GT0 * A0 * DSQRT(MAX(1D0+X**2+Y**2-2D0*(X+Y+X*Y),0D0))
      RETURN
      END

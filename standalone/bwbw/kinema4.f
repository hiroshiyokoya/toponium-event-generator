C
      SUBROUTINE PCM2HCM (X1,X2,P,PH)
      IMPLICIT NONE
      INTEGER I
      DOUBLE PRECISION X1,X2,P(0:3,6),PH(0:3,6),Q(0:3)
      Q(0) = X1+X2
      Q(1) = 0D0
      Q(2) = 0D0
      Q(3) = X1-X2
      DO I = 1, 6
         CALL BOOSTX (P(0,I),Q,PH(0,I))
      ENDDO
      RETURN
      END

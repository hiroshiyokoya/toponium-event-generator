      SUBROUTINE KINEMA6 (RS, MR1,MR2,MR3,MR4,
     -     COS1,PHI1,COS2,PHI2,COS3,PHI3,COS4,PHI4,COS5,PHI5, P)
      IMPLICIT NONE
      INTEGER I
      DOUBLE PRECISION RS,MR1,MR2,MR3,MR4
      DOUBLE PRECISION COS1,PHI1,COS2,PHI2,COS3,PHI3,COS4,PHI4,COS5,PHI5
      DOUBLE PRECISION P(0:3,8)
      DOUBLE PRECISION Q(0:3,4),PCM1(0:3),PCM2(0:3)
      DOUBLE PRECISION MT,MB,MW,GAMT,GAMW
      COMMON/MASS/MT,MB,MW,GAMT,GAMW
      CALL MOM2CX (RS,0D0,0D0,1D0,0D0,P(0,1),P(0,2)) ! g1 & g2
      CALL MOM2CX (RS,MR1,MR2,COS1,PHI1,Q(0,1),Q(0,2)) ! p_t & p_t~
      CALL MOM2CX (MR1,MB,MR3,COS2,PHI2,PCM1,PCM2)
      CALL BOOSTX (PCM1,Q(0,1),P(0,3)) ! p_b
      CALL BOOSTX (PCM2,Q(0,1),Q(0,3)) ! p_w+*
      CALL MOM2CX (MR2,MB,MR4,COS3,PHI3,PCM1,PCM2)
      CALL BOOSTX (PCM1,Q(0,2),P(0,6)) ! p_b~
      CALL BOOSTX (PCM2,Q(0,2),Q(0,4)) ! p_w-*
      CALL MOM2CX (MR3,0D0,0D0,COS4,PHI4,PCM1,PCM2)
      CALL BOOSTX (PCM1,Q(0,3),P(0,4)) ! p_mu+
      CALL BOOSTX (PCM2,Q(0,3),P(0,5)) ! p_vm
      CALL MOM2CX (MR4,0D0,0D0,COS5,PHI5,PCM1,PCM2)
      CALL BOOSTX (PCM1,Q(0,4),P(0,7)) ! p_mu-
      CALL BOOSTX (PCM2,Q(0,4),P(0,8)) ! p_vm~
      RETURN
      END

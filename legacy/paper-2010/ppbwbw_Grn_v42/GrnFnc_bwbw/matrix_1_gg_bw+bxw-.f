      SUBROUTINE GGTT (G1,G2,TP,TB,AMPT,AMPU,AMPS,ICLR)
      IMPLICIT NONE
      INTEGER ICLR
      DOUBLE COMPLEX G1(6),G2(6),TP(6),TB(6)
      DOUBLE COMPLEX AMPT,AMPU,AMPS,AMPT0,AMPU0
      DOUBLE COMPLEX W(6,3)
      include "coupl.inc"
      include "coupling.inc"
      INCLUDE "thr.inc"
      DOUBLE PRECISION ZERO
      PARAMETER (ZERO=0D0)
      DOUBLE COMPLEX GAMMA
      DOUBLE PRECISION MT1S,MT2S,S
      COMMON/BW/MT1S,MT2S,S
      DOUBLE PRECISION COR,CORR
      EXTERNAL CORR
C.....
      IF (ITR.EQ.0) THEN
         COR = 1D0
      ELSEIF (ITR.EQ.1) THEN
         COR = CORR (MT1S,MT2S,TMASS,TWIDTH,gfermi,WMASS,BMASS)
      ENDIF
C.....
      CALL FVIXXX (TB,G2,GG,TMASS,TWIDTH,W(1,1))
      CALL IOVXXX (W(1,1),TP,G1,GG,AMPT) ! t-channel
      CALL FVIXXX (TB,G1,GG,TMASS,TWIDTH,W(1,2))
      CALL IOVXXX (W(1,2),TP,G2,GG,AMPU) ! u-channel
      CALL JVVXXX (G1,G2,G ,ZERO ,ZERO  ,W(1,3))
      CALL IOVXXX (TB,TP,W(1,3),GG,AMPS) ! s-channel
      IF ( IGRN.EQ.1 ) THEN     ! OCP
         CALL GRNMOD (GAMMA,MT1S,MT2S,S,TMASS,ICLR)
         AMPT = AMPT * ( COR*GAMMA + (1D0-COR) * DBLE(INR) )
         AMPU = AMPU * ( COR*GAMMA + (1D0-COR) * DBLE(INR) )
         AMPS = AMPS * ( COR*GAMMA + (1D0-COR) * DBLE(INR) )
      ELSEIF ( IGRN.EQ.2 ) THEN ! TAP
         CALL FVIXXZ (TB,G2,GG,TMASS,TWIDTH,W(1,1))
         CALL IOVXXX (W(1,1),TP,G1,GG,AMPT0) ! t-channel
         CALL FVIXXZ (TB,G1,GG,TMASS,TWIDTH,W(1,2))
         CALL IOVXXX (W(1,2),TP,G2,GG,AMPU0) ! u-channel
         CALL GRNMOD (GAMMA,MT1S,MT2S,S,TMASS,ICLR)
         AMPT = ( AMPT0*GAMMA + AMPT - AMPT0 ) * COR +
     -        AMPT*(1D0-COR) * DBLE(INR)
         AMPU = ( AMPU0*GAMMA + AMPU - AMPU0 ) * COR +
     -        AMPU*(1D0-COR) * DBLE(INR)
      ENDIF
      RETURN
      END
C
      DOUBLE PRECISION FUNCTION CORR (S1,S2,MT,GT,GF,MW,MB)
      IMPLICIT NONE
      DOUBLE PRECISION S1,S2,MT,GT,GF,MW,MB
      DOUBLE PRECISION RUN,GT1,GT2
      EXTERNAL RUN
      GT1 = RUN(S1,MW,MB,GF)
      GT2 = RUN(S2,MW,MB,GF)
      CORR = DSQRT( MT*GT/(DSQRT(S1)*GT1) * MT*GT/(DSQRT(S2)*GT2) )
      RETURN
      END
C
      DOUBLE PRECISION FUNCTION RUN (P2,MW,MB,GF)
      IMPLICIT NONE
      DOUBLE PRECISION P2,MW,MB,GF
      DOUBLE PRECISION X,Y,GT0,A0
      DOUBLE PRECISION PI,SQ2
      PARAMETER ( PI=3.141592654D0,SQ2=1.41421356D0)
      X = MW**2/P2
      Y = MB**2/P2
      GT0 = GF/(8D0*SQ2*PI) * P2**1.5
      A0 = (1D0-Y)**2 + X*(1D0+Y) - 2D0*X**2
      RUN = GT0 * A0 * DSQRT( 1D0 + X**2 + Y**2 - 2D0*(X+Y+X*Y) )
      RETURN
      END
C
      SUBROUTINE GRNMOD (GAMMA,ST,SX,S,MT,ICLR)
      IMPLICIT NONE
      DOUBLE COMPLEX GAMMA
      DOUBLE PRECISION ST,SX,S,MT
      INTEGER ICLR
      DOUBLE PRECISION E,P
      DOUBLE PRECISION LAM,A,B,C
      INTEGER IFLG
      DATA IFLG/0/
      SAVE IFLG
      LAM(A,B,C) = DSQRT(MAX(0D0,A**2+B**2+C**2-2D0*(A*B+B*C+C*A)))
      IF (IFLG.NE.99) CALL SETUPGRN (IFLG,MT)
      E = S/(4D0*MT) - MT
      P = DSQRT(S)/2D0 * LAM(1D0,ST/S,SX/S)
      CALL READGRN (GAMMA,E,P,ICLR)
      RETURN
      END

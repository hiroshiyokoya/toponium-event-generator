      SUBROUTINE KINEMA4 (RS,MT1,MT2,COS1,PHI1,COS2,PHI2,COS3,PHI3,P)
      IMPLICIT NONE
      INTEGER I
      DOUBLE PRECISION RS,MT1,MT2,COS1,PHI1,COS2,PHI2,COS3,PHI3
      DOUBLE PRECISION P(0:3,6)
      DOUBLE PRECISION Q(0:3,2),PCM1(0:3),PCM2(0:3)
      DOUBLE PRECISION MT,MB,MW,GAMT
      COMMON/MASS/MT,MB,MW,GAMT
      CALL MOMNTX (RS/2D0,0D0, 1D0,0D0,P(0,1)) ! g1
      CALL MOMNTX (RS/2D0,0D0,-1D0,0D0,P(0,2)) ! g2
      CALL MOM2CX (RS,MT1,MT2,COS1,PHI1,Q(0,1),Q(0,2)) ! p_t & p_t~
      CALL MOM2CX (MT1,MB,MW,COS2,PHI2,PCM1,PCM2)
      CALL BOOSTX (PCM1,Q(0,1),P(0,3)) ! p_b
      CALL BOOSTX (PCM2,Q(0,1),P(0,4)) ! p_w+
      CALL MOM2CX (MT2,MB,MW,COS3,PHI3,PCM1,PCM2)
      CALL BOOSTX (PCM1,Q(0,2),P(0,5)) ! p_b~
      CALL BOOSTX (PCM2,Q(0,2),P(0,6)) ! p_w-
      RETURN
      END
